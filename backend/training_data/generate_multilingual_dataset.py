# Augmentation and expansion modifiers
INCOMPLETE_SUFFIXES = ["...", " aur fir...", " please...", " pata nahi...", " suno na...", " jaldi...", ""]
DISFLUENCY_PREFIXES = ["uh...", "um...", "actually...", "woh...", "suniye...", "hello...", ""]


def generate_samples_for_category(category: str, target_count: int = 150) -> List[Dict]:
    samples = []
    banks = DATA_BANKS.get(category, {})
    hi_seeds = banks.get("hi", [])
    hinglish_seeds = banks.get("hinglish", [])
    en_seeds = banks.get("en", [])

    all_seeds = [
        ("hi", hi_seeds),
        ("hinglish", hinglish_seeds),
        ("en", en_seeds),
    ]

    # Deterministic generation cycle
    idx = 0
    while len(samples) < target_count:
        for lang, seed_list in all_seeds:
            if len(samples) >= target_count:
                break
            base_sentence = seed_list[idx % len(seed_list)]

            # Style variance
            style_roll = (idx + len(category)) % 6
            text = base_sentence

            if style_roll == 0:
                # Conversational short utterance
                text = base_sentence.split(" और ")[0].split(" and ")[0].split(" but ")[0].strip()
                style = "short"
            elif style_roll == 1:
                # Disfluent / conversational speech
                prefix = random.choice(HINDI_PREFIXES if lang == "hi" else (HINGLISH_PREFIXES if lang == "hinglish" else ENGLISH_PREFIXES))
                text = f"{prefix} {base_sentence}".strip()
                style = "conversational"
            elif style_roll == 2:
                # Incomplete / hesitant speech
                suffix = random.choice(INCOMPLETE_SUFFIXES)
                text = f"{base_sentence}{suffix}".strip()
                style = "incomplete_hesitant"
            elif style_roll == 3:
                # Transliteration or spelling variation in Hinglish/English
                if lang == "hinglish":
                    text = base_sentence.replace("dhamki", "dhamkee").replace("darr", "dar").replace("bohot", "bahut").replace("bachao", "bachaoo")
                elif lang == "en":
                    text = base_sentence.replace("threatened", "threatnd").replace("police", "cops").replace("kill", "murder")
                else:
                    text = f"कृपया ध्यान दें... {base_sentence}"
                style = "spelling_variation"
            elif style_roll == 4:
                # Compound conversational sentence
                if lang == "hi":
                    text = f"{base_sentence}, मुझे बहुत चिंता हो रही है।"
                elif lang == "hinglish":
                    text = f"{base_sentence}, please kuch jaldi kijiye."
                else:
                    text = f"{base_sentence}, I am urgently asking for intervention."
                style = "compound_dialogue"
            else:
                # Standard seed
                text = base_sentence
                style = "standard"

            is_neutral = category in ["NEUTRAL_NO_INDICATOR", "CURRENT_SAFETY_REASSURANCE"]
            speaker_role = "operator" if "operator:" in text.lower() or "ऑपरेटर:" in text else "caller"

            samples.append({
                "id": f"{category[:4].lower()}_{len(samples) + 1:04d}",
                "text": text,
                "label": category,
                "language": lang,
                "style": style,
                "is_neutral_or_safe": is_neutral,
                "speaker_role": speaker_role,
            })
        idx += 1

    return samples[:target_count]


def generate_full_dataset(samples_per_category: int = 150) -> List[Dict]:
    """Generate balanced dataset across all 21 categories."""
    dataset = []
    for cat in CATEGORIES:
        cat_samples = generate_samples_for_category(cat, target_count=samples_per_category)
        dataset.extend(cat_samples)

    random.shuffle(dataset)
    for i, item in enumerate(dataset):
        item["id"] = f"SAATHI_{i+1:05d}"

    return dataset


def export_dataset():
    # 21 categories * 150 = 3,150 samples (satisfies >= 3,000 requirement)
    dataset = generate_full_dataset(samples_per_category=150)

    # Save JSON
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    # Save CSV
    with open(CSV_PATH, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["id", "text", "label", "language", "style", "is_neutral_or_safe", "speaker_role"])
        writer.writeheader()
        writer.writerows(dataset)

    print(f"Generated {len(dataset)} total samples across {len(CATEGORIES)} categories.")
    print(f"Saved to:\n  - {JSON_PATH}\n  - {CSV_PATH}")


if __name__ == "__main__":
    export_dataset()
